export function Dashboard({ snapshot }: { snapshot: SystemSnapshot | null }) {
  if (!snapshot) return null;
  const bar = (value: number, max = 100) => `${Math.min(100, (value / max) * 100)}%`;
  return (
    <aside className="panel panel-left dashboard">
      <header className="dash-head">
        <h3>System activity</h3>
        {snapshot.simulated && <span className="sim-badge">SIMULATED</span>}
      </header>
      <p className="dash-note">
        Not your machine. These values are generated by the backend to drive the visualization.
      </p>

      <div className="metric">
        <span>CPU</span>
        <div className="meter">
          <i style={{ width: bar(snapshot.cpu_usage) }} />
        </div>
        <b>{snapshot.cpu_usage.toFixed(0)}%</b>
      </div>
      <div className="metric-sub">{snapshot.cpu_frequency_ghz.toFixed(2)} GHz</div>

      <div className="cores" aria-label="Per-core utilisation">
        {snapshot.cores.map((core, index) => (
          <div key={index} className="core" title={`Core ${index}: ${core.toFixed(0)}%`}>
            <i style={{ height: `${core}%` }} />
          </div>
        ))}
      </div>

      <div className="metric">
        <span>GPU</span>
        <div className="meter">
          <i style={{ width: bar(snapshot.gpu_usage) }} />
        </div>
        <b>{snapshot.gpu_usage.toFixed(0)}%</b>
      </div>
      <div className="metric">
        <span>RAM</span>
        <div className="meter">
          <i style={{ width: bar(snapshot.ram_used_gb, snapshot.ram_total_gb) }} />
        </div>
        <b>
          {snapshot.ram_used_gb.toFixed(1)}/{snapshot.ram_total_gb}G
        </b>
      </div>
      <div className="metric">
        <span>VRAM</span>
        <div className="meter">
          <i style={{ width: bar(snapshot.vram_used_gb, snapshot.vram_total_gb) }} />
        </div>
        <b>
          {snapshot.vram_used_gb.toFixed(1)}/{snapshot.vram_total_gb}G
        </b>
      </div>
      <div className="metric-sub">
        Disk R {snapshot.storage_read_mbs.toFixed(0)} / W {snapshot.storage_write_mbs.toFixed(0)} MB/s ·
        Net {snapshot.network_mbps.toFixed(0)} Mb/s
      </div>
    </aside>
  );
}

/** Measured cache latency from c/cpuinfo.c -- real data from the build machine. */
export function LatencyChart({ data }: { data: LatencyData | null }) {
  if (!data || data.latency.length === 0) return null;
  const max = Math.max(...data.latency.map((sample) => sample.latency_ns));
  return (
    <div className="latency">
      <h3>Measured memory latency</h3>
      <p className="panel-note">
        Real measurement, not a diagram: <code>c/cpuinfo.c</code> pointer-chases a shuffled cycle so each
        load depends on the last, then times it at increasing working-set sizes. The steps are this
        machine's cache levels.
      </p>
      <div className="latency-bars">
        {data.latency.map((sample) => (
          <div key={sample.working_set_kb} className="latency-row">
            <span className="latency-size">
              {sample.working_set_kb >= 1024
                ? `${sample.working_set_kb / 1024}M`
                : `${sample.working_set_kb}K`}
            </span>
            <div className="latency-track">
              <i style={{ width: `${(sample.latency_ns / max) * 100}%` }} />
            </div>
            <span className="latency-value">{sample.latency_ns.toFixed(1)} ns</span>
          </div>
        ))}
      </div>
      <p className="panel-note">
        Cache layout reported by the kernel:{' '}
        {data.caches.map((cache) => `L${cache.level} ${cache.type[0]} ${cache.size_kb}KB`).join(' · ')}
      </p>
    </div>
  );
}

export function VoidtunePanel({
  info,
  groups,
  selectedCategory,
  onSelectCategory,
}: {
  info: VoidtuneInfo | null;
  groups: OptimizationGroup[];
  selectedCategory: string | null;
  onSelectCategory: (category: string | null) => void;
}) {
  if (!info) return null;
  const selected = groups.find((group) => group.category === selectedCategory) ?? null;
  return (
    <aside className="panel panel-right wide">
      <h2>{info.name}</h2>
      <p className="panel-short">
        v{info.version} · {info.platform} · {info.license}
      </p>
      <p>{info.summary}</p>

      <h3>What it does</h3>
      <ul>
        {info.what_it_does.map((item) => (
          <li key={item}>{item}</li>
        ))}
      </ul>
      <h3>What it does not do</h3>
      <ul className="negative">
        {info.what_it_does_not_do.map((item) => (
          <li key={item}>{item}</li>
        ))}
      </ul>

      <h3>
        Tweak catalog <span className="count">{info.total_tweaks} total</span>
      </h3>
      <p className="panel-note">
        Parsed directly from <code>TweakCatalog.cs</code> in the VOIDTUNE repo. Selecting a category
        highlights the component it affects in the scene.
      </p>
      <div className="chips">
        {groups.map((group) => (
          <button
            key={group.category}
            className={`chip ${selectedCategory === group.category ? 'on' : ''}`}
            onClick={() => onSelectCategory(selectedCategory === group.category ? null : group.category)}
          >
            {group.category} <b>{group.count}</b>
          </button>
        ))}
      </div>

      {selected && (
        <div className="tweak-list">
          <h3>
            {selected.category}
            {selected.component_id && <span className="count">affects {selected.component_id}</span>}
          </h3>
          {selected.tweaks.slice(0, 40).map((tweak) => (
            <div key={tweak.id} className="tweak">
              <div className="tweak-head">
                <b>{tweak.name}</b>
                <span className={`tier ${tweak.tier.toLowerCase()}`}>{tweak.tier.toUpperCase()}</span>
                {tweak.needs_reboot && <span className="tier reboot">REBOOT</span>}
              </div>
              <p>{tweak.description}</p>
            </div>
          ))}
          {selected.tweaks.length > 40 && (
            <p className="panel-note">+{selected.tweaks.length - 40} more in this category.</p>
          )}
        </div>
      )}
    </aside>
  );
}

/** Text-only rendering of every scene's content, shown when WebGL is
 * unavailable. The educational content must survive without 3D. */
