export function InfoPanel({
  component,
  onClose,
}: {
  component: PCComponent | null;
  onClose: () => void;
}) {
  if (!component) return null;
  return (
    <aside className="panel panel-right" aria-live="polite">
      <button className="panel-close" onClick={onClose} aria-label="Close information panel">
        ×
      </button>
      <h2>{component.name}</h2>
      <p className="panel-short">{component.short}</p>
      <p>{component.description}</p>
      {component.facts.length > 0 && (
        <>
          <h3>Worth knowing</h3>
          <ul>
            {component.facts.map((fact) => (
              <li key={fact}>{fact}</li>
            ))}
          </ul>
        </>
      )}
      {component.connects_to.length > 0 && (
        <>
          <h3>Connects to</h3>
          <p className="panel-tags">
            {component.connects_to.map((id) => (
              <span key={id} className="tag">
                {id.replace(/_/g, ' ')}
              </span>
            ))}
          </p>
        </>
      )}
    </aside>
  );
}

